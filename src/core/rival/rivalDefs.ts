/**
 * ライバル校の名前を作る。
 *
 * 固定の一覧を持たず、**語を組み合わせて作る**。
 * 一覧だと十数校で頭打ちになり、県が変わっても同じ顔ぶれになってしまう。
 * 実在校を想起させない一般的な語だけを使う（CLAUDE.md 5 参照）。
 */

import type { Rng } from '@/core/rng/random'

/** 校名の頭。地名めいた語と、学校らしい語を混ぜる */
const HEADS = [
  '青葉', '北嶺', '南陽', 'みどりヶ丘', '東雲', '白鷺', '桐生', '大空',
  '長峰', '若草', '海原', '星陵', '常磐', '藤代', '鷹取', '桜坂',
  '柏原', '深谷', '嵐山', '高砂', '有明', '双葉', '朝霧', '銀嶺',
  '天神', '碧洋', '紅葉', '相生', '鴻和', '芦原', '瑞穂', '光陵',
  '駿河', '宝陽', '文星', '成蹊野', '玉川台', '篠原', '牧野', '真岡',
]

/** 校名の後ろ。ここで学校の性格が変わる */
const TAILS = ['学院', '高校', '工業', '商業', '学園', '実業', '農業', '第一', '第二', '国際']

/**
 * 校名を1つ作る。すでに使われている名前は避ける。
 * 40 × 10 で400通りあるので、1県10校ならまず衝突しない。
 */
export function makeSchoolName(rng: Rng, taken: readonly string[]): string {
  let name = ''
  for (let i = 0; i < 30; i++) {
    name = `${rng.pick(HEADS)}${rng.pick(TAILS)}`
    if (!taken.includes(name)) return name
  }
  return name
}

