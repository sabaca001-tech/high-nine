/**
 * 地名を使う割合。
 * 全部を地名にすると実在校に寄りすぎるので、4校に3校程度に留める。
 */
const PLACE_NAME_RATE = 0.75

/**
 * 校名を1つ作る。すでに使われている名前は避ける。
 *
 * @param regionId 県。指定すると、その県らしい地名が混ざる
 */
export function makeSchoolName(
  rng: Rng,
  taken: readonly string[],
  regionId?: RegionId,
): string {
  const places = regionId ? (REGION_PLACES[regionId] ?? []) : []
  let name = ''

  for (let i = 0; i < 30; i++) {
    const usePlace = places.length > 0 && rng.chance(PLACE_NAME_RATE)
    const head = usePlace ? rng.pick(places) : rng.pick(GENERIC_HEADS)
    name = `${head}${rng.pick(TAILS)}`
    if (!taken.includes(name)) return name
  }
  return name
}

/** その県の地名（テストと表示の確認に使う） */
export function placesOf(regionId: RegionId): string[] {
  return REGION_PLACES[regionId] ?? []
}
