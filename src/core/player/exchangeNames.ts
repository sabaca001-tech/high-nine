/**
 * 留学生の名前。
 *
 * **実在の選手を想起させない、一般的な名前だけを使う**（CLAUDE.md 5）。
 *
 * **6文字まで使う。** 以前は4文字までに縛っていた。
 * カタカナは全角なので、「カルロス メンドーサ」のような名前は
 * 選手カードのネームプレートに収まらず、両方が切れて読めなくなったためだが、
 * そのせいで**留学生の名前がどれも短く、同じような響きに寄っていた**。
 *
 * 枠に入らないのは名前の側の問題ではなく**字の大きさの問題**なので、
 * 長い名前のときだけ字を小さくする（`nameFontSize`）ことで解いてある。
 *
 * 出身地は持たせない。国籍まで作り込むと、名前と国の対応が
 * おかしいときに嘘になるし、ゲームの判断には何も効かないため。
 */

import type { Rng } from '@/core/rng/random'

const SURNAMES = [
  'ロペス', 'ソーサ', 'クルス', 'リベラ', 'ゴメス', 'ペーニャ',
  'オルテガ', 'バルガス', 'キンタナ', 'セペダ', 'ナバロ', 'メヒア',
  'ブラウン', 'カーター', 'ハリス', 'ベネット', 'クラーク', 'ミラー',
  'ウォン', 'チェン', 'リン', 'ソン', 'キム', 'ジョ',
  // 長い姓。字を小さくすれば収まる
  'メンドーサ', 'サンチェス', 'ラミレス', 'カブレラ', 'エチェバリア',
  'エルナンデス', 'マルティネス', 'アンダーソン', 'ジョンソン', 'トンプソン',
  'ウィリアムズ', 'モンテーロ',
]

const GIVEN_NAMES = [
  'カルロス', 'ミゲル', 'パブロ', 'フリオ', 'オスカル', 'エミリオ',
  'ラウル', 'ディエゴ', 'マルコ', 'ペドロ', 'アベル', 'イバン',
  'ケビン', 'デビン', 'ジョン', 'ライアン', 'トマス', 'アーロン',
  'ネイサン', 'ルイス', 'ジュノ', 'ミンス', 'ウェイ', 'ハオ',
  // 長い名
  'アレハンドロ', 'フランシスコ', 'セバスチャン', 'クリスチャン',
  'マティアス', 'エステバン', 'ジャクソン', 'アンソニー',
  'ヨンジュン', 'ジュンホ', 'エドゥアルド', 'レアンドロ',
]

/** 生成を諦めて重複を許すまでの試行回数 */
const RETRY_LIMIT = 20

/**
 * 姓と名を合わせた長さの上限。
 *
 * **1つあたりの長さではなく、合わせた長さで縛る。**
 * 6文字の姓と6文字の名を引くと合計12文字になり、
 * いちばん小さい字（9px）でもネームプレートに収まらず、
 * 「クリスチ…／エルナン…」と両方が切れて誰なのか読めなくなる。
 * 10文字までなら収まることを実機（375px）で確かめてある。
 */
export const EXCHANGE_NAME_TOTAL_MAX = 10

/**
 * 留学生の名前を1つ選ぶ。「名 姓」の順で並べる。
 *
 * 長い名を引いたときは**姓を短いものから選ぶ**ので、
 * 「アレハンドロ ラミレス」は出るが「クリスチャン エルナンデス」は出ない。
 */
export function pickExchangeName(rng: Rng, taken: readonly string[]): string {
  let name = ''
  for (let i = 0; i < RETRY_LIMIT; i++) {
    const given = rng.pick(GIVEN_NAMES)
    const room = EXCHANGE_NAME_TOTAL_MAX - given.length
    const surnames = SURNAMES.filter((surname) => surname.length <= room)
    name = `${given} ${rng.pick(surnames.length > 0 ? surnames : SHORTEST_SURNAMES)}`
    if (!taken.includes(name)) return name
  }
  return name
}

/** 万一どの姓も入らないときの逃げ道。必ず名前を返す */
const SHORTEST_SURNAMES = [...SURNAMES].sort((a, b) => a.length - b.length).slice(0, 4)

/**
 * 名前が長すぎないことをテストで縛る。
 * **6文字が上限。** ここを超えると、いちばん小さい字でもネームプレートに入らない。
 */
export const EXCHANGE_NAME_MAX = 6
export const EXCHANGE_NAME_PARTS = { surnames: SURNAMES, givenNames: GIVEN_NAMES }
