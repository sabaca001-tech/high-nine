/**
 * 体力（`condition`）が何に効くか。
 *
 * **効き先を1か所に集める。** 練習の伸びだけが体力を見ていて、
 * しかも**70以上なら一律1.0**だったので、
 * 体力が70〜100を行き来する普段のプレイでは
 * 「休ませる」という判断に意味がほとんど無かった。
 * 怪我のほうは、**起きる確率が体力と無関係**で
 * （赤マスの4分の1で必ず発生し、誰が怪我するかだけ体力で決まっていた）、
 * チーム全員を疲れさせても怪我は増えなかった。
 *
 * 体力は「休むか、練習を積むか」を選ばせるための数字なので、
 * **伸びと怪我の両方**に効かせる。
 */

/**
 * 練習の伸びにかかる倍率。
 *
 * **段差をやめて、なだらかに効かせる。**
 * 70以上／40以上／20以上で 1.0 / 0.85 / 0.6 と刻んでいた頃は、
 * - 体力71と100で伸びがまったく同じ
 * - 体力70と69で 15% の差
 * という、どちらから見ても読めない効き方をしていた。
 *
 * | 体力 | 100 | 85 | 70 | 55 | 40 | 25 | 0 |
 * |---|---|---|---|---|---|---|---|
 * | 倍率 | 1.10 | 0.99 | 0.88 | 0.77 | 0.66 | 0.55 | 0.37 |
 *
 * **満タンなら1を超える。** 上限を1.0にすると、
 * 体力は「減ると損をする」だけの数字になり、
 * 休養カードは取り返すためだけの手になってしまう。
 */
export function conditionGrowthRate(condition: number): number {
  // **丸めない。** 1刻みでちゃんと差が出ないと、体力を1つ保つ意味が消える
  return CONDITION_FLOOR + (CONDITION_FULL - CONDITION_FLOOR) * (clamp(condition) / 100)
}

/** 体力0のときの倍率。**0にはしない**（練習そのものが消えると手が死ぬ） */
const CONDITION_FLOOR = 0.37

/** 体力100のときの倍率 */
const CONDITION_FULL = 1.1

/**
 * 怪我のしやすさ（0〜1）。**赤マスで怪我が起きるかの判定に使う。**
 *
 * 以前は赤マスの4分の1で**必ず**誰かが怪我をしていた。
 * 体力が効くのは「誰が怪我をするか」だけだったので、
 * チーム全体を疲れさせても怪我の件数は変わらず、
 * 体力を管理して怪我を防ぐ、ということができなかった。
 *
 * | 体力 | 100 | 80 | 60 | 40 | 20 | 0 |
 * |---|---|---|---|---|---|---|
 * | 怪我 | 35% | 48% | 61% | 74% | 87% | 100% |
 *
 * **万全でも0にはしない。** 怪我が完全に消せると、
 * 体力を保つことが「絶対に取るべき手」になって選択でなくなる。
 */
export function injuryRiskOf(condition: number): number {
  return INJURY_RISK_FULL + (1 - INJURY_RISK_FULL) * (1 - clamp(condition) / 100)
}

/** 体力100の選手が怪我をする確率 */
const INJURY_RISK_FULL = 0.35

/**
 * 怪我をする選手の選ばれやすさ。**体力が低いほど大きい。**
 * 誰が怪我をするかは、以前からこの重みで決めている。
 */
export function injuryWeightOf(condition: number): number {
  return Math.max(1, 110 - clamp(condition))
}

function clamp(condition: number): number {
  return Math.min(100, Math.max(0, condition))
}
